import type { ForwardClosedTrade, ForwardPosition } from "@/lib/forward-state";

export type TradingViewExportOptions = {
  symbol?: string;
  intervalMinutes?: number;
  maxTrades?: number;
};

export type TradeMarker = {
  entryMs: number;
  exitMs: number;
  entryPrice: number;
  exitPrice: number;
  side: "long" | "short";
  strategyId: string;
  exitReason: string;
  open: boolean;
};

/** Matches Hyro / Bybit USDT linear on TradingView */
const DEFAULT_SYMBOL = "BYBIT:BTCUSDT.P";

export function tradingViewChartUrl(symbol = DEFAULT_SYMBOL): string {
  return `https://www.tradingview.com/chart/?symbol=${encodeURIComponent(symbol)}`;
}

export function tradingViewChartUrlForTime(iso: string, symbol = DEFAULT_SYMBOL): string {
  const ms = Date.parse(iso);
  if (Number.isNaN(ms)) return tradingViewChartUrl(symbol);
  // TradingView accepts approximate navigation via anchor on some builds; symbol link is always valid.
  return `${tradingViewChartUrl(symbol)}&interval=3#${Math.floor(ms / 1000)}`;
}

export function markersFromForward(
  history: ForwardClosedTrade[],
  positions: ForwardPosition[],
  opts?: TradingViewExportOptions,
): TradeMarker[] {
  const max = opts?.maxTrades ?? 80;
  const closed: TradeMarker[] = history.slice(0, max).map((t) => ({
    entryMs: Date.parse(t.opened_at),
    exitMs: Date.parse(t.closed_at),
    entryPrice: t.entry_price,
    exitPrice: t.exit_price,
    side: t.side,
    strategyId: t.strategy_id,
    exitReason: t.exit_reason,
    open: false,
  }));
  const open: TradeMarker[] = positions.map((p) => ({
    entryMs: Date.parse(p.opened_at),
    exitMs: Date.now(),
    entryPrice: p.entry_price,
    exitPrice: p.mark_price,
    side: p.side,
    strategyId: p.strategy_id,
    exitReason: "open",
    open: true,
  }));
  return [...open, ...closed].filter((m) => !Number.isNaN(m.entryMs));
}

function pineNum(n: number): string {
  if (!Number.isFinite(n)) return "na";
  const s = n.toFixed(8);
  return s.replace(/\.?0+$/, "") || "0";
}

function pineStr(s: string): string {
  return `"${s.replace(/\\/g, "\\\\").replace(/"/g, '\\"')}"`;
}

/** Pine v5 indicator — paste in TradingView → Pine Editor → Add to chart. */
export function buildPineScript(markers: TradeMarker[], opts?: TradingViewExportOptions): string {
  const symbol = opts?.symbol ?? DEFAULT_SYMBOL;
  const barMs = (opts?.intervalMinutes ?? 3) * 60_000;
  const entries = markers.map((m) => m.entryMs);
  const exits = markers.map((m) => (m.open ? m.entryMs + barMs : m.exitMs));
  const entryPx = markers.map((m) => m.entryPrice);
  const exitPx = markers.map((m) => m.exitPrice);
  const isLong = markers.map((m) => m.side === "long");
  const tags = markers.map(
    (m) => `${m.strategyId}${m.open ? " · OPEN" : ` · ${m.exitReason}`} · ${m.side}`,
  );

  if (markers.length === 0) {
    return `//@version=5
indicator("AAR trades (empty)", overlay=true)
// No trades to plot — run forward test or export again after closes.`;
  }

  return `//@version=5
indicator("AAR forward trades", overlay=true, max_labels_count=500, max_lines_count=500)

// Generated by AAR dashboard — research / review only
// Chart symbol: ${symbol}  ·  bar tolerance: ${opts?.intervalMinutes ?? 3}m
// Cursor: copy this file from GET /api/trades/tradingview?format=pine

var int[] ENTRIES = array.from(${entries.join(", ")})
var int[] EXITS = array.from(${exits.join(", ")})
var float[] ENTRY_PX = array.from(${entryPx.map(pineNum).join(", ")})
var float[] EXIT_PX = array.from(${exitPx.map(pineNum).join(", ")})
var bool[] IS_LONG = array.from(${isLong.join(", ")})
var string[] TAGS = array.from(${tags.map(pineStr).join(", ")})

int BAR_MS = ${barMs}

bool near(int t) =>
    not na(t) and math.abs(time - t) <= BAR_MS

if barstate.isconfirmed
    for i = 0 to array.size(ENTRIES) - 1
        int et = array.get(ENTRIES, i)
        int xt = array.get(EXITS, i)
        if near(et)
            bool lng = array.get(IS_LONG, i)
            float ep = array.get(ENTRY_PX, i)
            string tg = array.get(TAGS, i)
            label.new(
                 bar_index, ep,
                 "E " + tg,
                 style = lng ? label.style_label_up : label.style_label_down,
                 color = lng ? color.new(color.teal, 20) : color.new(color.orange, 20),
                 textcolor = color.white,
                 size = size.small)
        if near(xt) and xt != et
            bool lng2 = array.get(IS_LONG, i)
            float xp = array.get(EXIT_PX, i)
            label.new(
                 bar_index, xp,
                 "X " + array.get(TAGS, i),
                 style = lng2 ? label.style_label_down : label.style_label_up,
                 color = color.new(color.gray, 30),
                 textcolor = color.white,
                 size = size.tiny)
`;
}

export function buildTradesCsv(markers: TradeMarker[]): string {
  const header = "opened_at,closed_at,side,strategy,entry_price,exit_price,status,exit_reason";
  const rows = markers.map((m) => {
    const opened = new Date(m.entryMs).toISOString();
    const closed = m.open ? "" : new Date(m.exitMs).toISOString();
    return [
      opened,
      closed,
      m.side,
      m.strategyId,
      m.entryPrice,
      m.exitPrice,
      m.open ? "open" : "closed",
      m.exitReason,
    ].join(",");
  });
  return [header, ...rows].join("\n");
}
